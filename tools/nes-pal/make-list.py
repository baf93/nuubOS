# Writes package/nuubos/nuubos-emulation/src/nes-pal.conf from the No-Intro
# NES DAT of libretro-database (metadat/no-intro): the headerless (.unh)
# CRC32 of every dump whose name regions are all PAL countries, unless the
# same CRC is also listed under a non-PAL name. docs/dev/emulation.md.
# Run: python3 -I tools/nes-pal/make-list.py DAT DAT_VERSION COMMIT > package/nuubos/nuubos-emulation/src/nes-pal.conf
import collections, re, sys

PAL = {'Europe', 'Australia', 'Germany', 'France', 'Italy', 'Spain', 'Sweden',
       'United Kingdom', 'UK', 'Netherlands', 'Scandinavia', 'Denmark', 'Finland',
       'Norway', 'Portugal', 'Greece', 'Austria', 'Switzerland', 'Belgium',
       'New Zealand', 'Poland'}

if len(sys.argv) != 4:
    sys.exit('usage: make-list.py DAT DAT_VERSION LIBRETRO_DATABASE_COMMIT')
dat, version, commit = sys.argv[1:]
text = open(dat, encoding='utf-8').read()
kinds, names = collections.defaultdict(set), {}
for m in re.finditer(r'game \(\n\tname "([^"]*)"\n(?:.*\n)*?\trom \( name "[^"]*\.unh" size \d+ crc ([0-9A-F]{8})', text):
    name, crc = m.group(1), m.group(2).lower()
    group = re.search(r'\(([^)]*)\)', name)
    regions = {r.strip() for r in group.group(1).split(',')} if group else set()
    kinds[crc].add(bool(regions) and regions <= PAL)
    names.setdefault(crc, name)

print('''# NES releases that exist only as PAL (50 Hz) carts: CRC32 of the ROM without
# its 16-byte iNES header, then the No-Intro name. nuubos-emud sets the FCEUmm
# core option fceumm_region to PAL for these games when the user left it on
# Auto: FCEUmm detects PAL only from (E)/(Europe)/(PAL) in the file name or a
# NES 2.0 header, and a renamed PAL dump otherwise runs 20 %% fast at 60 Hz.
# Names whose regions are all PAL countries (Europe, Australia, France,
# Germany, Italy, Spain, Sweden, UK, ...); multi-region dumps (USA, Europe)
# and famiclone regions (Russia, Asia) stay on Auto.
#
# Data: No-Intro "Nintendo - Nintendo Entertainment System" DAT %s from
# libretro-database (metadat/no-intro, commit %s),
# https://github.com/libretro/libretro-database, licensed CC BY-SA 4.0
# (LICENSE-CC-BY-SA-4.0.txt); this list is an adaptation under the same license.
# Generated by tools/nes-pal/make-list.py.''' % (version, commit))
for crc in sorted(c for c, k in kinds.items() if k == {True}):
    print(crc, names[crc])
